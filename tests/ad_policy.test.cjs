const assert=require('node:assert/strict');
const {AdPolicy}=require('../experiments/ad_policy.js');
const p=new AdPolicy();
const ctx={consentAllowsRequest:true,sdkReady:true,gameplayActive:false,firstSession:false};
assert.equal(p.canInterstitial({...ctx,nowSeconds:200}),false);
p.gameEnded();p.gameEnded();
assert.equal(p.canInterstitial({...ctx,nowSeconds:200}),false);
p.gameEnded();
assert.equal(p.canInterstitial({...ctx,gameplayActive:true,nowSeconds:200}),false);
assert.equal(p.canInterstitial({...ctx,consentAllowsRequest:false,nowSeconds:200}),false);
assert.equal(p.canInterstitial({...ctx,nowSeconds:200}),true);
p.interstitialShown(200);
p.gameEnded();p.gameEnded();p.gameEnded();
assert.equal(p.canInterstitial({...ctx,nowSeconds:300}),false);
assert.equal(p.canInterstitial({...ctx,nowSeconds:380}),true);
assert.equal(p.offerRewarded({runId:'a',explicitOptIn:false,consentAllowsRequest:true,sdkReady:true}),false);
assert.equal(p.offerRewarded({runId:'a',explicitOptIn:true,consentAllowsRequest:true,sdkReady:true}),true);
assert.equal(p.rewardEarned('b'),false);
assert.equal(p.rewardEarned('a'),true);
assert.equal(p.rewardEarned('a'),false);
assert.equal(p.offerRewarded({runId:'a',explicitOptIn:true,consentAllowsRequest:true,sdkReady:true}),false);
assert.equal(p.offerRewarded({runId:'b',explicitOptIn:true,consentAllowsRequest:true,sdkReady:true}),true);
p.rewardedDismissed();
assert.equal(p.rewardEarned('b'),false);
console.log('PASS: consent / gameplay safety / cooldown / one reward');
